_LANGUAGE = "zh"


def _detect_language() -> str:
    global _LANGUAGE
    for candidate in (Path("config.yaml"), Path.home() / ".lmloader" / "config.yaml"):
        try:
            if not candidate.exists():
                continue
            cfg = yaml.safe_load(candidate.read_text(encoding="utf-8")) or {}
            lang = (cfg.get("ui") or {}).get("language", "zh")
            if lang in TRANSLATIONS:
                _LANGUAGE = lang
                return lang
        except Exception:
            continue
    _LANGUAGE = "zh"
    return "zh"


def get_language() -> str:
    return _LANGUAGE


def set_language(lang: str):
    global _LANGUAGE
    if lang in TRANSLATIONS:
        _LANGUAGE = lang


def tr(key: str) -> str:
    """Translate a UI key in the current language; falls back to en, then the key."""
    table = TRANSLATIONS.get(_LANGUAGE, TRANSLATIONS["zh"])
    return table.get(key, TRANSLATIONS["en"].get(key, key))


